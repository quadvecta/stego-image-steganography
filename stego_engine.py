"""
STEGO engine (v1.0) — no Tk dependency, fully unit-testable.

Design
------
Token      : 32 random bytes (urlsafe-b64, 44 chars). This IS the secret; it has a full
             256 bits of entropy because it is generated by os.urandom, not typed by a human.
             (v0.x used a 16-byte *salt* as both password and salt for PBKDF2 — the 100k
             iterations bought nothing because the token holder, or anyone who saw the
             token, could re-derive everything instantly. A random key needs no stretching.)
Key split  : HKDF-SHA256(token, info=...) -> three independent 32-byte keys:
               enc  : Fernet key (AES-128-CBC + HMAC-SHA256, authenticated)
               scat : ChaCha20 key driving the pixel-selection permutation
               mac  : HMAC key authenticating the embedded header
Scatter    : ChaCha20 keystream -> one uint64 sort key per pixel -> stable argsort.
             Deterministic, keyed, prefix-stable (first k indices identical for any k).
Embedding  : 2 LSBs of the BLUE channel (OpenCV BGR index 0), 4 pixels per payload byte,
             MSB-first. Output image has the same dimensions as the input.
Layout     : [MAGIC 3][VER 1][CT_LEN 4][HDR_TAG 8][FERNET_CIPHERTEXT]
             No salt is stored in the image. Without the token the header positions are
             unknown, so a wrong token produces garbage that fails magic/tag checks.

Compatibility: images made by v0.x (salt-token, PBKDF2 scatter) are NOT decodable here.
"""

import base64
import hashlib
import hmac
import os
import secrets
import stat
import struct
import tempfile
from dataclasses import dataclass, field
from typing import Optional

import cv2
import numpy as np
from cryptography.fernet import Fernet, InvalidToken
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

MAGIC = b"ST2"
VERSION = 2
TOKEN_BYTES = 32
TAG_BYTES = 8
HEADER_BYTES = len(MAGIC) + 1 + 4 + TAG_BYTES          # 16
BITS_PER_PIXEL = 2
PIXELS_PER_BYTE = 8 // BITS_PER_PIXEL                  # 4
CHANNEL_INDEX = 0                                      # BGR -> blue
METHOD_LABEL = "2-LSB, blue channel, keyed scatter"
LOSSLESS_EXT = (".png", ".bmp")
LOSSY_EXT = (".jpg", ".jpeg")


class StegoError(Exception):
    """Any user-actionable engine failure."""


class SaveVerificationError(StegoError):
    pass


# ───────────────────────── key handling ─────────────────────────

def new_token() -> str:
    return base64.urlsafe_b64encode(secrets.token_bytes(TOKEN_BYTES)).decode()


def parse_token(token: str) -> bytes:
    try:
        raw = base64.urlsafe_b64decode(token.strip() + "=" * (-len(token.strip()) % 4))
    except Exception:
        raise StegoError("Invalid key token — it is not valid base64.")
    if len(raw) != TOKEN_BYTES:
        if len(raw) == 16:
            raise StegoError("This looks like a v0.x key token (24 chars). Images made by "
                             "older STEGO versions use a different scheme and cannot be "
                             "decoded by this version.")
        raise StegoError(f"Invalid key token length: got {len(raw)} bytes, expected {TOKEN_BYTES}.")
    return raw


def _derive(secret: bytes):
    okm = HKDF(algorithm=hashes.SHA256(), length=96, salt=None,
               info=b"STEGO-v2 key schedule").derive(secret)
    return base64.urlsafe_b64encode(okm[:32]), okm[32:64], okm[64:96]   # enc, scat, mac


# ───────────────────────── scatter ─────────────────────────

def scatter_order(n_pixels: int, scat_key: bytes) -> np.ndarray:
    """
    Keyed pseudorandom permutation of range(n_pixels) (stable argsort of ChaCha20-derived
    64-bit keys). Same key + n_pixels -> same permutation; callers take a prefix.
    """
    enc = Cipher(algorithms.ChaCha20(scat_key, b"\x00" * 16), mode=None).encryptor()
    stream = enc.update(bytes(8 * n_pixels))
    keys = np.frombuffer(stream, dtype=np.uint64)
    return np.argsort(keys, kind="stable").astype(np.int64)


# ───────────────────────── bit packing ─────────────────────────

def _bytes_to_dibits(data: bytes) -> np.ndarray:
    a = np.frombuffer(data, dtype=np.uint8)
    return np.stack([(a >> 6) & 3, (a >> 4) & 3, (a >> 2) & 3, a & 3], axis=1).reshape(-1)


def _dibits_to_bytes(d: np.ndarray) -> bytes:
    d = d.reshape(-1, 4).astype(np.uint8)
    return ((d[:, 0] << 6) | (d[:, 1] << 4) | (d[:, 2] << 2) | d[:, 3]).astype(np.uint8).tobytes()


def _embed(flat: np.ndarray, positions: np.ndarray, payload: bytes) -> None:
    d = _bytes_to_dibits(payload)
    assert len(d) == len(positions)
    ch = flat[positions, CHANNEL_INDEX]
    flat[positions, CHANNEL_INDEX] = (ch & 0xFC) | d


def _extract(flat: np.ndarray, positions: np.ndarray) -> bytes:
    return _dibits_to_bytes(flat[positions, CHANNEL_INDEX] & 0x03)


def _tag(mac_key: bytes, ct_len: int) -> bytes:
    return hmac.new(mac_key, MAGIC + bytes([VERSION]) + struct.pack(">I", ct_len),
                    hashlib.sha256).digest()[:TAG_BYTES]


# ───────────────────────── capacity ─────────────────────────

def fernet_overhead() -> int:
    """Fernet ciphertext (urlsafe-b64 text) length for an empty plaintext."""
    return len(Fernet(Fernet.generate_key()).encrypt(b""))


def fernet_len(plain_len: int) -> int:
    block = 16
    padded = (plain_len // block + 1) * block
    raw = 1 + 8 + 16 + padded + 32
    return 4 * ((raw + 2) // 3)


def required_pixels(plain_len: int) -> int:
    return (HEADER_BYTES + fernet_len(plain_len)) * PIXELS_PER_BYTE


def max_plaintext_bytes(shape) -> int:
    n = shape[0] * shape[1]
    avail = n // PIXELS_PER_BYTE - HEADER_BYTES
    best = 0
    lo, hi = 0, max(avail, 0)
    while lo <= hi:
        mid = (lo + hi) // 2
        if HEADER_BYTES + fernet_len(mid) <= n // PIXELS_PER_BYTE:
            best, lo = mid, mid + 1
        else:
            hi = mid - 1
    return best


# ───────────────────────── result object ─────────────────────────

@dataclass
class EncodeResult:
    img_out: np.ndarray
    cover: np.ndarray
    token: str
    positions: np.ndarray            # flat pixel indices actually written, in write order
    n_header_pixels: int             # first n_header_pixels positions carry header bytes
    plaintext_bytes: int
    ciphertext_bytes: int
    shape: tuple
    method: str = METHOD_LABEL
    channel: str = "Blue (BGR index 0), 2 LSBs"
    output_path: Optional[str] = None
    output_format: Optional[str] = None
    output_bytes: Optional[int] = None
    verified: bool = False

    @property
    def n_pixels_total(self): return self.shape[0] * self.shape[1]
    @property
    def n_pixels_used(self): return len(self.positions)
    @property
    def header_positions(self): return self.positions[:self.n_header_pixels]
    @property
    def payload_positions(self): return self.positions[self.n_header_pixels:]
    @property
    def pixel_fraction(self): return self.n_pixels_used / self.n_pixels_total
    @property
    def channel_bit_fraction(self):
        # bits of capacity touched: 2 bits per used pixel, out of 8 bits x 3 channels per pixel
        return (self.n_pixels_used * BITS_PER_PIXEL) / (self.n_pixels_total * 24)


# ───────────────────────── encode / decode ─────────────────────────

def _check_image(img) -> None:
    if (not isinstance(img, np.ndarray) or img.dtype != np.uint8
            or img.ndim != 3 or img.shape[2] != 3 or img.shape[0] < 1 or img.shape[1] < 1):
        raise StegoError("Unsupported image: expected an 8-bit, 3-channel (BGR) image.")


def stego_encode(img_bgr: np.ndarray, plaintext: str) -> EncodeResult:
    _check_image(img_bgr)
    pt = plaintext.encode("utf-8")
    h, w = img_bgr.shape[:2]
    n = h * w
    need = required_pixels(len(pt))
    if need > n:
        raise StegoError(
            f"Message too large: needs {need:,} pixels, image has {n:,}. "
            f"Max message for this image ≈ {max_plaintext_bytes(img_bgr.shape):,} bytes (UTF-8).")

    token = new_token()
    secret = parse_token(token)
    fkey, scat, mac = _derive(secret)
    ct = Fernet(fkey).encrypt(pt)
    header = MAGIC + bytes([VERSION]) + struct.pack(">I", len(ct)) + _tag(mac, len(ct))
    payload = header + ct
    assert len(payload) * PIXELS_PER_BYTE == need

    order = scatter_order(n, scat)
    positions = order[:need].copy()

    out = np.ascontiguousarray(img_bgr).copy()
    flat = out.reshape(-1, 3)
    _embed(flat, positions, payload)

    return EncodeResult(img_out=out, cover=img_bgr.copy(), token=token, positions=positions,
                        n_header_pixels=HEADER_BYTES * PIXELS_PER_BYTE,
                        plaintext_bytes=len(pt), ciphertext_bytes=len(ct), shape=(h, w, 3))


def stego_decode(img_bgr: np.ndarray, token: str) -> str:
    _check_image(img_bgr)
    secret = parse_token(token)
    fkey, scat, mac = _derive(secret)
    h, w = img_bgr.shape[:2]
    n = h * w
    if n < HEADER_BYTES * PIXELS_PER_BYTE:
        raise StegoError("Image is too small to contain a STEGO payload.")
    order = scatter_order(n, scat)
    flat = np.ascontiguousarray(img_bgr).reshape(-1, 3)

    hdr = _extract(flat, order[:HEADER_BYTES * PIXELS_PER_BYTE])
    fail = "No valid STEGO payload found — wrong key, wrong image, or the image was modified/recompressed."
    if hdr[:3] != MAGIC or hdr[3] != VERSION:
        raise StegoError(fail)
    ct_len = struct.unpack(">I", hdr[4:8])[0]
    if not hmac.compare_digest(hdr[8:16], _tag(mac, ct_len)):
        raise StegoError(fail)
    if ct_len == 0 or (HEADER_BYTES + ct_len) * PIXELS_PER_BYTE > n:
        raise StegoError("Corrupted payload header (length exceeds image capacity).")

    total = HEADER_BYTES + ct_len
    raw = _extract(flat, order[:total * PIXELS_PER_BYTE])
    try:
        return Fernet(fkey).decrypt(raw[HEADER_BYTES:]).decode("utf-8")
    except InvalidToken:
        raise StegoError("Authentication failed — the embedded data is corrupted or has been altered.")
    except UnicodeDecodeError:
        raise StegoError("Decrypted data is not valid UTF-8 text.")


# ───────────────────────── image I/O ─────────────────────────

def read_image(path: str) -> np.ndarray:
    """Unicode-safe read, forced to 8-bit 3-channel BGR (alpha, if any, is dropped)."""
    try:
        data = np.fromfile(path, dtype=np.uint8)
    except Exception as e:
        raise StegoError(f"Cannot open file: {e}")
    if data.size == 0:
        raise StegoError("File is empty or unreadable.")
    img = cv2.imdecode(data, cv2.IMREAD_COLOR)
    if img is None:
        raise StegoError("Unsupported or corrupted image file.")
    return img


def save_and_verify(res: EncodeResult, path: str) -> EncodeResult:
    """
    Stage, fsync and verify an image before atomically replacing the destination.
    Compare its decoded message to the original in-memory decode. Failures remove
    only our temporary file and leave the destination and prior result metadata unchanged.
    Existing targets must be writable. Preserve supported mode bits, not old times;
    Windows chmod only controls the read-only flag. Ownership, ACLs, xattrs and other
    platform-specific metadata are not guaranteed to survive atomic replacement.
    """
    ext = os.path.splitext(path)[1].lower()
    if ext in LOSSY_EXT:
        params = [cv2.IMWRITE_JPEG_QUALITY, 100]
    elif ext == ".png":
        params = [cv2.IMWRITE_PNG_COMPRESSION, 6]
    elif ext == ".bmp":
        params = []
    else:
        raise StegoError(f"Unsupported output format '{ext}'. Use .png (recommended) or .bmp.")

    temp_path = None
    try:
        expected = stego_decode(res.img_out, res.token)
        ok, buf = cv2.imencode(ext, res.img_out, params)
        if not ok:
            raise SaveVerificationError("Image encoder reported failure.")
        data = buf.tobytes()
        with tempfile.NamedTemporaryFile(mode="wb", prefix=".stego-", suffix=ext,
                                         dir=os.path.dirname(os.path.abspath(path)),
                                         delete=False) as f:
            temp_path = f.name
            if f.write(data) != len(data):
                raise SaveVerificationError("Incomplete image write.")
            f.flush()
            os.fsync(f.fileno())
        output_bytes = os.path.getsize(temp_path)
        if output_bytes == 0 or output_bytes != len(data):
            raise SaveVerificationError("Temporary output is empty or incomplete.")
        try:
            back = read_image(temp_path)
        except StegoError as e:
            raise SaveVerificationError(f"Saved file could not be reopened: {e}") from e
        if back.shape != res.img_out.shape:
            raise SaveVerificationError("Saved image dimensions differ from the encoded image.")
        if ext in LOSSLESS_EXT and not np.array_equal(back, res.img_out):
            raise SaveVerificationError("Saved image does not match the encoded pixels.")
        try:
            msg = stego_decode(back, res.token)
        except StegoError as e:
            raise SaveVerificationError(
                "The saved image does not decode (JPEG recompression destroys LSB data). "
                "Save as PNG instead. The destination was not changed.") from e
        if msg != expected:
            raise SaveVerificationError("Saved message differs from the encoded message.")
        try:
            mode = stat.S_IMODE(os.stat(path).st_mode)
        except FileNotFoundError:
            mode = None
        if mode is not None:
            # Directory write permission alone can replace a read-only file.
            if (not os.access(path, os.W_OK)
                    or (os.name == "posix" and (mode & 0o222) == 0)):
                raise SaveVerificationError("Existing destination is read-only or not writable.")
            os.chmod(temp_path, mode)
            if os.name == "posix" and stat.S_IMODE(os.stat(temp_path).st_mode) != mode:
                raise SaveVerificationError("Could not preserve destination permission bits.")
        os.replace(temp_path, path)
        temp_path = None
    except SaveVerificationError:
        raise
    except Exception as e:
        raise SaveVerificationError(f"Could not save and verify image: {e}") from e
    finally:
        if temp_path is not None:
            try:
                os.unlink(temp_path)
            except FileNotFoundError:
                pass
            except OSError as e:
                raise SaveVerificationError(
                    f"Could not remove temporary output '{temp_path}': {e}") from e

    res.output_path = path
    res.output_format = ext.lstrip(".").upper()
    res.output_bytes = output_bytes
    res.verified = True
    return res


# ───────────────────────── heatmap ─────────────────────────

def _positive_int(value, name):
    if (isinstance(value, (bool, np.bool_))
            or not isinstance(value, (int, np.integer)) or value < 1):
        raise StegoError(f"{name} must be a positive integer.")
    return int(value)


def _checked_positions(shape, positions):
    try:
        h, w = shape[:2]
    except (TypeError, ValueError):
        raise StegoError("Image shape must contain height and width.")
    h, w = _positive_int(h, "Height"), _positive_int(w, "Width")
    if positions is None:
        raise StegoError("No embedding positions recorded - cannot build a heatmap.")
    try:
        positions = np.asarray(positions)
    except (TypeError, ValueError) as e:
        raise StegoError("Recorded positions must be a one-dimensional integer array.") from e
    if positions.size == 0:
        raise StegoError("No embedding positions recorded - cannot build a heatmap.")
    if positions.ndim != 1 or positions.dtype.kind not in "iu":
        raise StegoError("Recorded positions must be a one-dimensional integer array.")
    if positions.min() < 0 or positions.max() >= h * w:
        raise StegoError("Recorded positions fall outside the image bounds.")
    return h, w, positions.astype(np.intp, copy=False)


def _check_density(grid):
    if (not isinstance(grid, np.ndarray) or grid.ndim != 2
            or grid.dtype.kind not in "biuf"):
        raise StegoError("Density must be a two-dimensional real numeric array.")
    if grid.min(initial=0) < 0 or not np.isfinite(grid).all():
        raise StegoError("Density must contain finite, nonnegative counts.")


def position_counts(shape, positions: np.ndarray) -> np.ndarray:
    """Exact per-pixel hit map (H x W, int32). Nonzero support == embedded positions."""
    h, w, positions = _checked_positions(shape, positions)
    counts = np.zeros(h * w, dtype=np.int32)
    np.add.at(counts, positions, 1)
    return counts.reshape(h, w)


def auto_bin(shape) -> int:
    """Bin edge (px) so the density grid is roughly 40-80 cells on the long side."""
    return max(1, int(round(max(shape[:2]) / 64)))


def bin_density(counts: np.ndarray, bin_px: int) -> np.ndarray:
    """Sum counts in bin_px x bin_px blocks (exact aggregation, edge blocks included)."""
    bin_px = _positive_int(bin_px, "Bin size")
    _check_density(counts)
    h, w = counts.shape
    bh, bw = -(-h // bin_px), -(-w // bin_px)
    if counts.size == 0:
        return np.zeros((bh, bw), dtype=np.float64)
    binned = np.empty((bh, bw), dtype=np.float64)
    columns = np.arange(0, w, bin_px)
    for row in range(bh):
        totals = counts[row * bin_px:(row + 1) * bin_px].sum(axis=0, dtype=np.float64)
        binned[row] = np.add.reduceat(totals, columns)
    return binned


def position_density(shape, positions: np.ndarray, bin_px: int) -> np.ndarray:
    """Float64 binned hit counts, including duplicates, without an H x W hit map.

    Equivalent to bin_density(position_counts(shape, positions), bin_px).
    Missing/empty positions are rejected, just as in position_counts.
    """
    bin_px = _positive_int(bin_px, "Bin size")
    h, w, positions = _checked_positions(shape, positions)
    bh, bw = -(-h // bin_px), -(-w // bin_px)
    cells = (positions // w // bin_px) * bw + positions % w // bin_px
    return np.bincount(cells, minlength=bh * bw).reshape(bh, bw).astype(np.float64)


def render_heatmap(cover: np.ndarray, binned: np.ndarray, bin_px: int,
                   overlay: bool = True, alpha: float = 0.6, max_dim: int = 560):
    """
    Returns (bgr_image, vmin, vmax). Density is binned embed-count per cell, normalised
    min..max over the grid. Constant positive grids use the high colour; zero grids
    use the low colour. Empty/invalid grids raise StegoError. Preview coordinates
    map through image pixels and bin_px, preserving clipped edge cells without a
    full-resolution expansion. Display only - inputs are never modified.
    """
    _check_image(cover)
    bin_px = _positive_int(bin_px, "Bin size")
    max_dim = _positive_int(max_dim, "Preview size")
    _check_density(binned)
    if (not isinstance(alpha, (int, float, np.integer, np.floating))
            or not 0 <= alpha <= 1):
        raise StegoError("Overlay alpha must be between 0 and 1.")
    h, w = cover.shape[:2]
    if binned.shape != (-(-h // bin_px), -(-w // bin_px)):
        raise StegoError("Density grid dimensions do not match the image and bin size.")
    vmin, vmax = float(binned.min()), float(binned.max())
    if vmax == vmin:
        norm = np.full(binned.shape, float(vmax > 0))
    else:
        norm = (binned.astype(np.float64) - vmin) / (vmax - vmin)
    u8 = (norm * 255).astype(np.uint8)
    scale = min(1.0, max_dim / max(h, w))
    tw, th = max(1, int(w * scale)), max(1, int(h * scale))
    xs = (np.arange(tw, dtype=np.int64) * w // tw) // bin_px
    ys = (np.arange(th, dtype=np.int64) * h // th) // bin_px
    big = u8[ys[:, None], xs[None, :]]
    heat = cv2.applyColorMap(big, cv2.COLORMAP_INFERNO)
    if overlay:
        base = cv2.resize(cover, (tw, th), interpolation=cv2.INTER_AREA)
        heat = cv2.addWeighted(base, 1 - alpha, heat, alpha, 0)
    return heat, vmin, vmax


def colorbar(height: int, width: int = 18) -> np.ndarray:
    g = np.linspace(255, 0, height).astype(np.uint8).reshape(-1, 1)
    return cv2.applyColorMap(np.repeat(g, width, axis=1), cv2.COLORMAP_INFERNO)


def to_png_b64(img_bgr: np.ndarray) -> str:
    ok, buf = cv2.imencode(".png", img_bgr)
    if not ok:
        raise StegoError("Could not render preview.")
    return base64.b64encode(buf.tobytes()).decode()


# ───────────────────────── cover vs stego analysis ─────────────────────────

def compare(cover: np.ndarray, stego: np.ndarray) -> dict:
    if cover.shape != stego.shape:
        raise StegoError("Cover and stego images have different dimensions/channels.")
    d = cover.astype(np.int16) - stego.astype(np.int16)
    mse = float(np.mean(d.astype(np.float64) ** 2))
    psnr = float("inf") if mse == 0 else 10 * np.log10(255.0 ** 2 / mse)
    return {"mae": float(np.mean(np.abs(d))), "mse": mse, "psnr": psnr,
            "changed_pixels": int(np.count_nonzero(np.any(d != 0, axis=2))),
            "changed_fraction": float(np.mean(np.any(d != 0, axis=2))),
            "max_abs_diff": int(np.abs(d).max())}


def diff_image(cover: np.ndarray, stego: np.ndarray, max_dim: int = 560) -> np.ndarray:
    """Absolute difference, amplified x85 so 1..3 LSB deltas are visible (display only)."""
    d = np.abs(cover.astype(np.int16) - stego.astype(np.int16)).max(axis=2)
    img = np.clip(d * 85, 0, 255).astype(np.uint8)
    h, w = img.shape
    s = min(1.0, max_dim / max(h, w))
    if s < 1.0:
        k = int(np.ceil(1.0 / s))                      # max-pool so sparse changes stay visible
        img = cv2.dilate(img, np.ones((k, k), np.uint8))
        img = cv2.resize(img, (max(1, int(w * s)), max(1, int(h * s))),
                         interpolation=cv2.INTER_NEAREST)
    return cv2.cvtColor(img, cv2.COLOR_GRAY2BGR)


def histogram_plot(cover: np.ndarray, stego: np.ndarray, size=(520, 200)) -> np.ndarray:
    """Blue-channel histograms, cover (dim) vs stego (bright). Visual aid only."""
    W, H = size
    canvas = np.full((H, W, 3), (26, 14, 10), np.uint8)
    hc = cv2.calcHist([cover], [0], None, [256], [0, 256]).ravel()
    hs = cv2.calcHist([stego], [0], None, [256], [0, 256]).ravel()
    top = max(hc.max(), hs.max(), 1)
    for hist, col in ((hc, (120, 90, 40)), (hs, (255, 212, 0))):
        pts = np.array([[int(i * (W - 1) / 255), int(H - 1 - (v / top) * (H - 8))]
                        for i, v in enumerate(hist)], np.int32)
        cv2.polylines(canvas, [pts], False, col, 1, cv2.LINE_AA)
    return canvas
